static float log2_P2_16(float x)
{
    int i; LEGACY_F2I(i, x);
    int k = i & 0x007fffff;
    int j =k>>19;
    k = c0[j] + k*(c1[j] - c2[j]*k);
    k = 0x3f800000|k;
    float y; LEGACY_I2F(y, k);
    y = y + logbf(x)-1;
    return y;
}



