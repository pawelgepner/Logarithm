static float log2_Mitchell(float x)
       {
       int i; LEGACY_F2I(i, x);
       int m = i & 0x007fffff;
       i = i >> 23;
       i = i-128;
       m = 0x3f800000|m;
       float y; LEGACY_I2F(y, m);
       y = y + i;
      return y;
      }



