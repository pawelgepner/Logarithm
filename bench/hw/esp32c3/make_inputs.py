"""Write main/inputs.h: the same 1000 inputs per kind as bench/emu.py (seed 2026)."""
import random
from pathlib import Path

def inputs(kind, n, rng):          # identical to bench/emu.py
    if kind == "float":
        return [((127 + rng.randrange(-20, 20)) << 23) | rng.getrandbits(23) for _ in range(n)]
    if kind == "frac":
        return [rng.getrandbits(23) for _ in range(n)]
    if kind == "u32":
        return [(1 << (b - 1)) | rng.getrandbits(b - 1) if b > 1 else 1
                for b in (rng.randrange(1, 33) for _ in range(n))]
    if kind == "q31":
        return [(1 << (b - 1)) | rng.getrandbits(b - 1) if b > 1 else 1
                for b in (rng.randrange(1, 32) for _ in range(n))]

rng = random.Random(2026)
out = ["/* Generated by make_inputs.py: inputs of bench/emu.py, seed 2026. */",
       "#include <stdint.h>"]
for kind in ("float", "frac", "u32", "q31"):
    xs = inputs(kind, 1000, rng)
    body = ",\n".join("  " + ", ".join(f"0x{x:08X}u" for x in xs[i:i + 8]) for i in range(0, len(xs), 8))
    out.append(f"static const uint32_t in_{kind}[1000] = {{\n{body}\n}};")
    out.append(f"#define IN_{kind.upper()}_DATA in_{kind}")
Path(__file__).with_name("main").joinpath("inputs.h").write_text("\n".join(out) + "\n")
print("main/inputs.h written")
